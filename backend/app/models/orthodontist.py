from sqlalchemy import Column, String, Integer, SMALLINT, Boolean, Date, DateTime, Numeric, Text, func
from sqlalchemy.dialects.postgresql import UUID, ARRAY
import uuid
from ..database import Base
class Orthodontist(Base):
    __tablename__ = "orthodontists"
    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now())
    first_name = Column(String(100), nullable=False)
    last_name = Column(String(100), nullable=False)
    email = Column(String(254), unique=True, nullable=False)
    phone = Column(String(20), nullable=True)
    rpps_number = Column(String(11), unique=True, nullable=True)
    years_of_experience = Column(SMALLINT, nullable=True)
    installation_year = Column(SMALLINT, nullable=True)
    practice_name = Column(String(200), nullable=False)
    city = Column(String(100), nullable=False)
    department = Column(String(3), nullable=False)
    region = Column(String(100), nullable=False)
    practice_type = Column(String(20), nullable=False)
    num_practitioners = Column(SMALLINT, nullable=False, default=1)
    num_secretaries = Column(SMALLINT, nullable=False, default=0)
    active_patients_estimate = Column(Integer, nullable=True)
    current_software = Column(String(100), nullable=True)
    uses_quote_software = Column(Boolean, nullable=False, default=False)
    uses_voice_dictation = Column(Boolean, nullable=False, default=False)
    offers_teleconsultation = Column(Boolean, nullable=False, default=False)
    member_of_pro_association = Column(Boolean, nullable=False, default=False)
    pro_association_name = Column(String(200), nullable=True)
    part_of_dental_network = Column(Boolean, nullable=False, default=False)
    dental_network_name = Column(String(200), nullable=True)
    linkedin_url = Column(String(500), nullable=True)
    linkedin_followers = Column(Integer, nullable=True)
    linkedin_activity = Column(String(20), nullable=False, default='none')
    instagram_url = Column(String(500), nullable=True)
    instagram_followers = Column(Integer, nullable=True)
    instagram_activity = Column(String(20), nullable=False, default='none')
    website_url = Column(String(500), nullable=True)
    website_quality = Column(String(20), nullable=False, default='none')
    google_reviews_count = Column(Integer, nullable=True)
    google_reviews_avg = Column(Numeric(2, 1), nullable=True)
    has_presented_webinar = Column(Boolean, nullable=False, default=False)
    has_given_keynote = Column(Boolean, nullable=False, default=False)
    conferences = Column(ARRAY(Text), nullable=False, default=[])
    publications = Column(ARRAY(Text), nullable=False, default=[])
    teaches_at_university = Column(Boolean, nullable=False, default=False)
    university_name = Column(String(200), nullable=True)
    source = Column(String(20), nullable=False, default='other')
    assigned_to = Column(String(100), nullable=True)
    contact_status = Column(String(30), nullable=False, default='not_contacted')
    contact_date = Column(Date, nullable=True)
    next_follow_up = Column(Date, nullable=True)
    email_opened = Column(Boolean, nullable=False, default=False)
    email_link_clicked = Column(Boolean, nullable=False, default=False)
    demo_attended = Column(Boolean, nullable=False, default=False)
    notes = Column(Text, nullable=True)
    manual_tier_override = Column(String(20), nullable=True)
    prospect_score = Column(SMALLINT, nullable=False, default=0)
    tier = Column(String(20), nullable=False, default='standard')
